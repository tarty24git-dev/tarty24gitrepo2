-- Oracle Database DDL and Initial DML Script for CTH Enterprise Platform

-- Table: cth_users
CREATE TABLE cth_users (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(100) NOT NULL UNIQUE,
    password VARCHAR2(255) NOT NULL,
    full_name VARCHAR2(150),
    email VARCHAR2(150),
    phone_number VARCHAR2(50),
    role VARCHAR2(50) DEFAULT 'ROLE_USER',
    locked NUMBER(1,0) DEFAULT 0,
    enabled NUMBER(1,0) DEFAULT 1,
    password_last_changed TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    password_expiration_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP + 90,
    require2fa NUMBER(1,0) DEFAULT 0
);

-- Table: cth_report_configs
CREATE TABLE cth_report_configs (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_name VARCHAR2(150) NOT NULL UNIQUE,
    description VARCHAR2(500),
    table_name VARCHAR2(100) NOT NULL,
    selected_fields VARCHAR2(2000) NOT NULL,
    filter_condition VARCHAR2(1000),
    order_by_field VARCHAR2(500),
    sort_direction VARCHAR2(10) DEFAULT 'ASC',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Table: cth_db_configs
CREATE TABLE cth_db_configs (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    db_type VARCHAR2(50) DEFAULT 'ORACLE',
    host VARCHAR2(100) DEFAULT 'localhost',
    port NUMBER(5,0) DEFAULT 1521,
    database_name VARCHAR2(100) DEFAULT 'ORCL',
    username VARCHAR2(100) DEFAULT 'system',
    password VARCHAR2(100),
    jdbc_url VARCHAR2(500),
    driver_class_name VARCHAR2(150) DEFAULT 'oracle.jdbc.OracleDriver'
);

